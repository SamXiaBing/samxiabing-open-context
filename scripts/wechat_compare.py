def norm(s: str) -> str:
    s = s.lower().replace("some/ip", "someip")
    return re.sub(r"[^0-9a-z\u4e00-\u9fff]", "", s)


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    catalog = [json.loads(l) for l in (ROOT / "catalog.local.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    by_norm = {norm(r["title"]): r for r in catalog}
    matched, missing = [], []
    for title, date in WECHAT:
        row = by_norm.get(norm(title))
        if row:
            matched.append((title, date, row))
        else:
            missing.append((title, date))
    matched_keys = {norm(t) for t, _, _ in matched}
    extras = [r for r in catalog if norm(r["title"]) not in matched_keys]

    print(f"清单 {len(WECHAT)} 篇：匹配 {len(matched)}，清单有但语料库没有 {len(missing)}")
    for t, d in missing:
        print(f"  [清单缺失] {t} {d}")
    print(f"\n语料库多出（不在 91 清单内）{len(extras)} 篇：")
    for r in extras:
        print(f"  [语料多出] {r['title']}  tier={r['visibility']} mtime={r['date']}")

    out = {"matched": [{"wechat": t, "date": d, "path": r["path"]} for t, d, r in matched],
           "missing": [{"title": t, "date": d} for t, d in missing],
           "extras": [{"title": r["title"], "path": r["path"], "visibility": r["visibility"]} for r in extras]}
    (ROOT / "wechat_compare.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\n明细 → wechat_compare.json")


if __name__ == "__main__":
    main()
